/**
 * 판(버전)과 그 판에서 무엇이 바뀌었는지.
 *
 * **왜 이 파일이 따로 있는가.** 그동안 고칠 것을 고쳐 올려도 판 번호는 0.9.0
 * 그대로였다. 그러면 화면에 적힌 `0.9.0 (12)` 이 서로 다른 열 개의 앱을
 * 가리키게 되어, "고친 게 안 보여요"라는 말을 들었을 때 정말 안 받은 것인지
 * 받았는데 안 고쳐진 것인지를 가릴 수가 없다.
 *
 * 그래서 판을 올릴 때마다 여기에 한 줄씩 남긴다. 화면의 판 표시를 누르면
 * 이 목록이 그대로 나온다 — 지금 쓰는 앱이 무엇을 담고 있는지 폰만 보고
 * 알 수 있어야 하기 때문이다.
 *
 * ── 판을 올릴 때 ─────────────────────────────────────────────
 *
 *   1. app.json 의 expo.version 을 올린다
 *   2. 여기 APP_VERSION 도 같은 값으로 올린다
 *   3. RELEASES 맨 앞에 이번 판을 넣는다
 *
 * 1과 2가 어긋나면 테스트(changelog.test.ts)가 잡는다. 사람이 기억해서
 * 지키는 규칙은 반드시 언젠가 깨지기 때문에 검사로 못박아 둔다.
 *
 * 화면(react-native)을 안 쓰는 순수 데이터라 폰 없이 테스트할 수 있다.
 */

export interface Release {
  /** 0.10.0 */
  version: string;
  /** yyyy-mm-dd */
  date: string;
  /** 이 판을 한 줄로 하면 */
  title: string;
  /** 바뀐 것들. 아이도 부모도 읽는 자리라 기능 이름이 아니라 겪는 말로 적는다. */
  items: string[];
}

