/**
 * 숙어의 첫 낱말이 불규칙 동사면 그것도 바꿔야 한다.
 * (take part in → took part in, give up → gave up)
 */
export function irregularOf(word: string): string[] {
  return IRREGULAR_FORMS[word.toLowerCase()] ?? [];
}
