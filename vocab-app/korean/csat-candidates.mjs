/** [{ word, hanja, domain }] 로 펼친다. */
export function candidates() {
  const out = [];
  for (const [domain, blob] of Object.entries(DOMAINS)) {
    const tokens = blob.trim().split(/\s+/);
    for (let i = 0; i < tokens.length; i += 2) {
      const word = tokens[i];
      const hanja = tokens[i + 1];
      // '-' 는 한자가 없는 낱말(외래어·고유어)이라는 표시다.
      out.push({ word, hanja: hanja === '-' ? '' : hanja, domain });
    }
  }
  return out;
}
