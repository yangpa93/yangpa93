/**
 * 굽는 순간의 시각을 앱 안에 박아 넣는다.
 *
 * ── 왜 필요한가 ─────────────────────────────────────────────
 *
 * 판 정보에 「0.23.0.17 · 2026.08.16.13.45」 처럼 만든 때를 적는다. 빌드
 * 번호만으로는 그것이 언제 것인지 알 수 없어서다 — 하루에 두어 번 구운
 * 날에는 아이 폰에 든 것이 아침 것인지 저녁 것인지 번호로 못 가린다.
 *
 * 그 시각을 `Updates.createdAt` 에서 읽고 있었다. 그런데 그 값은 **무선
 * 업데이트로 받은 판**의 것이고, APK 를 갓 깔아 그것을 그대로 돌리는
 * 동안에는 비어 있을 수 있다. "버전 정보에 빌드 시간이 다시 없어졌습니다"
 * 라는 말을 들은 자리가 여기다 — 새 APK 를 깔고 열었을 때다.
 *
 * 그래서 굽는 쪽에서 한 번 더 적어 둔다. 이 파일은 **구울 때마다 새로
 * 평가되므로** 그때의 시각이 그대로 박힌다.
 *
 * ── app.json 은 그대로 둔다 ─────────────────────────────────
 *
 * expo 가 app.json 을 먼저 읽어 `config` 로 넘겨 준다. 여기서는 그 위에
 * 시각 한 줄만 얹는다. 설정을 두 곳에 나눠 적으면 한쪽만 고치는 일이
 * 반드시 생긴다.
 */
module.exports = ({ config }) => ({
  ...config,
  extra: {
    ...config.extra,
    /*
     * ISO 로 적는다. 사람이 읽을 모양(`2026.08.16.13.45`)으로 바꾸는 일은
     * 앱 쪽에서 한다 — 폰의 시간대로 읽어야 그 폰 주인에게 맞는 시각이 된다.
     */
    builtAt: new Date().toISOString(),
  },
});
