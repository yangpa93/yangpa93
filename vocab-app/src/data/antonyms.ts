/** 그 단어의 반대말들. 없으면 빈 배열. */
export function antonymsOf(word: string): string[] {
  return ANTONYMS[word.toLowerCase()] ?? [];
}

/** 반대말 문제를 낼 수 있는 단어인지. */
export function hasAntonym(word: string): boolean {
  return antonymsOf(word).length > 0;
}
