/** 판을 숫자 셋으로 가른다. 0.10.0 이 0.9.0 보다 뒤라는 것을 글자 비교로는 알 수 없다. */
function parts(version: string): number[] {
  return version.split('.').map((n) => {
    const v = Number(n);
    return Number.isFinite(v) ? v : 0;
  });
}

/**
 * 판 비교. a 가 뒤면 양수, 앞이면 음수, 같으면 0.
 *
 * 글자로 비교하면 '0.10.0' < '0.9.0' 이 되어 새 판이 옛 판보다 앞에 선다.
 * 자리마다 숫자로 봐야 한다.
 */
export function compareVersions(a: string, b: string): number {
  const x = parts(a);
  const y = parts(b);
  const len = Math.max(x.length, y.length);
  for (let i = 0; i < len; i++) {
    const d = (x[i] ?? 0) - (y[i] ?? 0);
    if (d !== 0) return d;
  }
  return 0;
}

/** 가장 새 판. 목록이 비어 있으면 null — 화면이 죽지 않도록. */
export function latestRelease(): Release | null {
  return RELEASES[0] ?? null;
}

